/*
 * The size and the shape of the guides themselves, and so the one gate whose
 * subject is this repository's own documentation (#821). The root guide held
 * 198,202 characters before it, most of them a per-module archive loaded on
 * every turn, including every turn that never opens the module; and the gate
 * that read that file then — holding its counts of `ATTRIBUTES` and `PATTERNS`
 * to the lists in the code — said nothing at all about its size, in the file
 * that says every convention must be machine-enforced.
 *
 * What answers it is a relocation and never a summary, those derivations being
 * what stops a later session loosening a bar that was placed on evidence: each
 * note moved into the `CLAUDE.md` of the directory its module sits in, where
 * it arrives when that directory is opened, and the root keeps the rules, the
 * bars, and one line per file. `LOADED` is the 150,000 characters the harness
 * warns past, and what arrives against it is a **chain** and not a pair: the
 * root guide, and the guide of every directory on the way down to a file the
 * turn touches, each injected once. That was measured rather than assumed —
 * two throwaway guides planted at `src/resources/` and
 * `src/resources/motives/`, neither of them ever read as a file, both arrived
 * the moment a motive under them was opened. The first spelling of the bar
 * weighed the root against the dearest single guide instead, which is a whole
 * directory short: it read 130,933 and called that 0.87 of the bar while a
 * turn touching `src/linters/` was loading 157,504 and over it. So the two
 * dearest notes moved one step further down, out of `src/CLAUDE.md` and into
 * the top of `src/grammar.js` and `src/syntax.js` — 24,681 characters. A turn
 * under `test/` or `src/linters/` has run it close ever since, and the dearest
 * reads 136,706, which is 0.91. What answers a chain reaching the bar is that
 * move again, a module's derivation into the file-header note of the module
 * itself, and never a bar widened to fit what has grown past it: a docblock
 * holds five lines of description since #832, so prose that has outgrown a
 * guide does not simply move into one instead. A `CEILING` of half the bar
 * stood beside it until it was seen to be a gate no tree could fail: the root
 * stands in every chain, so the chain holding it above weighs each other guide
 * against the bar less what stands over it — 26,351 for
 * `src/linters/CLAUDE.md`, where half of the bar is 75,000 — and holds the
 * root itself to 81,686, a number derived from the dearest chain rather than
 * chosen. A gate no tree can fail is removed and not kept (#750, #660).
 *
 * All four of those figures — the chain, its ratio, and the two allowances —
 * follow from three file sizes, so one guide growing moves every one of them,
 * and none of them turned red when one did: #811's fourth phase added 3,421
 * characters to `src/CLAUDE.md` and left the chain reading 140,286 where two
 * documents still said 136,418, the allowances 3,868 out, and the ratio 0.94
 * where three places said 0.91. The bar itself was quiet throughout, as it is
 * until 150,000, which is why this is the third time the same class of figure
 * has drifted. `DERIVED` in `test/guides.js` holds each of them now, red from
 * both sides in the way `SPRAWLING` and `UNINDEXED` are: a figure the tree
 * disagrees with fails, and so does a figure standing in a document the row
 * does not name, since a claim nobody is reading is not a claim being kept.
 * That second half is a **set** and not an `any`, which is the whole of it —
 * the chain and its ratio are carried twice, one carrier having spelled its
 * half "the dearest chain is that same one at" where `test/guides.js` says
 * "the dearest reads", so a gate asking whether *some* file still matches was
 * satisfied by the untouched one. Rewording only the first, to say 136,418 and
 * 0.91 again, left the figure wrong by 3,868 and the ratio by 0.03 with the
 * suite reading 16 passing: the drift gate had stopped reading that sentence
 * and the anchor gate was happy off the other file. Each row therefore names
 * every file expected to carry it and the matched set is compared whole, so
 * rewording either carrier fails, and so does the claim appearing in a
 * document no row names. Growing a guide by 4,000 characters fails all five
 * rows at once. The asking is `matchAll` and never `test`, a global pattern
 * leaving `lastIndex` where it stopped and answering `false` to the very next
 * question about the same prose.
 *
 * The paragraph above stopped being advice while this change was being
 * written: #846 grew `src/linters/CLAUDE.md` by 3,113 and the merged chain
 * read 150,437, so the bar failed on a tree whose two authors had each stayed
 * under it. The prescribed relief is the one taken — `src/predicates.js`'s
 * derivation went into the file-header note of `src/predicates.js`, 2,507
 * characters out of the chain and none out of the record — which is the third
 * note to move that way after `src/grammar.js` and `src/syntax.js`, and the
 * first to move because the bar said so rather than in the change that wrote
 * it. It said so a merge too late, though, which is the half #844 answers: a
 * gate that fires on the breach fires where the relief no longer fits, the
 * tree having to be red for as long as a relocation takes to land. `ROOM`
 * moves it off the breach, 10,000 characters of headroom, so a chain reddens
 * at 140,000 while there is still room to answer it. It moves the bar rather
 * than standing a second one beside it: a breach gate left at 150,000 could
 * not fire while this one is green, which is what took `CEILING` out, so the
 * two are one gate whose message names both numbers. It is measured off the
 * tree's own growth rather than picked: over the 45 merges between #823 giving
 * the chain its room back and this one, the most a day of ordinary work added
 * to the dearest chain was 5,298, and 10,000 is 1.89 of that — inside the
 * half-again-to-twice band every bar here answers to, and held to it from both
 * sides by `GROWN`, since a margin under half again of a day is one a day
 * crosses without warning and one past twice it reddens a tree with room to
 * spare. A day is the unit because that is what a relocation takes to land,
 * this tree merging three to eight times in one.
 *
 * Eleven notes moved to make the bar quiet — `xpath-linter.js`,
 * `root-template-linter.js`, `corpus-linter.js` and `output-linter.js` out of
 * `src/linters/CLAUDE.md`, and `scaling.test.js`, `predicates.test.js`,
 * `helpers.js`, `grammar-corpus.test.js`, `grammar-shapes.test.js`,
 * `workflows.test.js` and this note out of `test/CLAUDE.md`. One was refused
 * by the valve rather than chosen against: `test/conformance.test.js` stands
 * at 926 lines and its note is 150 more, and `max-lines` counts comments, so a
 * section can outgrow the file it is about and relief has a floor — what
 * answers that one is the note being cut, not moved. Before those eleven the
 * root gave a note up too: the merge behind #811's bracket phase breached the
 * bar by 844 with neither branch having crossed it alone, so the
 * `src/xslint.js` derivation went into `src/CLAUDE.md` — 2,147 characters out
 * of every chain but the three standing under `src/`, of which #877 spent
 * 1,910 and #856 left 53. The last two moved together, and for the plainest
 * reason yet: #884 gave `scripts/` a third script and so the root a third row,
 * and the root stands in every chain, so 141 characters written there put
 * `test/`'s chain 88 past the bar and left `src/linters/`'s 18 short of it — a
 * margin the next sentence anybody writes spends. Relief taken out of one
 * guide answers for that guide alone, which is why the dearest note of each
 * went down a directory rather than the dearest of the two, 8,565 and 3,276
 * characters out of the chains and none out of the record. What that leaves is
 * 3,294 characters of headroom, off `src/linters/`'s chain rather than
 * `test/`'s again, and what answers the next red is the move again, on the
 * dearest note the guide that reddens holds rather than on the newest. It is a
 * fifth figure of the same class as the four, and the one that proves the
 * point twice over — it stood outside the table and drifted 418 behind the
 * rows in it with every one of them green, so it has a row of its own since
 * #856.
 *
 * The index answers to the tree from both sides, every path it names existing
 * and every module under `src/` being named by a row — the twenty-one linters
 * by one of them, the `*` standing for a name and never for a directory — and
 * a note answers to the index and to its own directory both, so a derivation
 * the root has stopped pointing at turns red, and so does one standing where
 * the reader who needs it will never load it. `test/guides.js` is the walk
 * itself rather than a list of the five, since a guide left off a hand-written
 * list would take its claims out of every gate at once, and the reading of a
 * claim stands beside the walk: `worded` flattening a wrapped paragraph into
 * one line, `DOCUMENTS` naming the guides and the README together, `NEARBY`
 * bounding how far past a name a number may stand and still be a claim about
 * it. Both gates ask it, so a count relocated into a guide is judged where it
 * went, and so is the length a guide states of the file the line cap is lifted
 * off, which is `test/conformance.test.js`'s to ask beside the cap it is an
 * exemption from. The counts came the other way at that same sitting:
 * `ATTRIBUTES` and `PATTERNS` are held to the lists in the code from here now,
 * the file that held them having reached the 1000 lines it caps every other
 * file at (#825).
 */

const {allFilesFrom} = require('../src/helpers')
const {ATTRIBUTES, PATTERNS} = require('../src/attributes')
const {kinds} = require('../src/resources/checks.json')
const {splitOf} = require('../src/selectors')
const {GAP} = require('../src/tokens')
const {
  ROOT, GUIDES, DOCUMENTS, DERIVED, LOADED, ROOM, NEARBY, carries, slashed,
  sized, worded, chained, loaded, indexed, noted, globbed,
} = require('./guides')
const path = require('path')
const assert = require('assert')

/**
 * The prose read whole, every count in it being a count of one of the two
 * lists: the module holding them. A number written beside a list is a fact that
 * rots — three places said `ATTRIBUTES` held nineteen names where it has held
 * twenty since #633, one of them wrong on the day the list grew (#654).
 * @type {Array.<string>}
 */
const PROSE = ['src/attributes.js']

/**
 * Where a figure derived from what the guides weigh may stand: the documents,
 * and the two modules doing the weighing — the note above among them, four of
 * the five figures having moved into it when this chain reddened.
 * @type {Array.<string>}
 */
const MEASURED = DOCUMENTS.concat(['test/guides.js', 'test/guides.test.js'])

/**
 * The most a day of ordinary work has added to the dearest chain since #823
 * gave that chain its room back, read over the 45 merges between then and #844.
 * A day is the unit because a relocation lands in about one, this tree taking
 * three to eight merges a day, so it is what a chain has to survive between
 * turning red and being answered.
 * @type {number}
 */
const GROWN = 5298

/**
 * The selectors a shared walk cannot serve as an axis, which is what
 * `UNINDEXED` in `test/conformance.test.js` lists and what a guide counts
 * beside that name. Read off the checks rather than off the table, the table
 * answering to the same checks one gate over, so prose, code and table are one
 * chain rather than two claims about each other.
 * @return {number} - How many of them there are
 */
const unindexed = function() {
  return Object.values(kinds.xpath).filter(
    (check) => splitOf(check.xpath).length === 0,
  ).length
}

/**
 * Each list as a document may name it, paired with what it holds. `NAMED` is
 * `ATTRIBUTES` as a set, so it counts to the same and answers to a claim about
 * either name.
 * @type {Map.<string, number>}
 */
const LENGTHS = new Map([
  ['ATTRIBUTES', ATTRIBUTES.length],
  ['PATTERNS', PATTERNS.length],
  ['NAMED', ATTRIBUTES.length],
  ['UNINDEXED', unindexed()],
])

/**
 * The words a count is spelled with, paired with what each counts to. A `Map`
 * and not an object, because membership is the whole of what is asked of it and
 * `'constructor' in {}` answers true: an object judges a claim about "the
 * constructor names" against `Object` itself rather than reading past a word
 * that is no number, so the prototype chain decides what the prose is about.
 * @type {Map.<string, number>}
 */
const NUMBERS = new Map([
  'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine',
  'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen',
  'seventeen', 'eighteen', 'nineteen', 'twenty', 'twenty-one', 'twenty-two',
  'twenty-three',
].map((word, index) => [word, index + 1]))

describe('guides', function() {
  it('walks the tree for the guides standing beside the code', function() {
    assert.ok(
      GUIDES.length > 1,
      'cannot find a guide beside the code it is about, this walk having ' +
        `found ${GUIDES.join(', ')} and nothing else — the derivation behind ` +
        'a module lives in the CLAUDE.md of its own directory since #821, so ' +
        'a walk reaching only the root one leaves every claim in the others ' +
        'judged by nobody',
    )
  })
  it('cannot come within reach of what a turn may load', function() {
    assert.deepEqual(
      GUIDES.filter((one) => loaded(one) > LOADED - ROOM).map(
        (one) => `${one} loads ${loaded(one)} in ${
          chained(one).map((each) => `${each} at ${sized(each)}`).join(' + ')}`,
      ),
      [],
      `cannot load a chain of guides within ${ROOM} characters of the ` +
        `${LOADED} the harness warns at, a turn touching a file loading the ` +
        'root guide and the guide of every directory over it — the bar ' +
        `stands at ${LOADED - ROOM} so that a derivation still has somewhere ` +
        'to go when it fires, what answers it being that derivation moving ' +
        'one directory further down, into the file-header note of the module ' +
        'it is about, and never a bar widened to fit what has grown past it',
    )
  })
  it('keeps room enough to answer a chain that has reached the bar', function() {
    assert.ok(
      ROOM >= GROWN * 1.5 && ROOM <= GROWN * 2,
      `cannot keep ${ROOM} characters under the bar against a dearest day ` +
        `of ${GROWN}: a margin under half again of it is one a single day of ` +
        'work crosses without warning, and one past twice it reddens a tree ' +
        'that has room to spare, both of which are a bar that has stopped ' +
        'being one',
    )
  })
  it('names in its index only files the tree holds', function() {
    for (const row of indexed()) {
      assert.ok(
        allFilesFrom(path.join(ROOT, path.dirname(row)))
          .map(slashed).some((one) => globbed(row).test(one)),
        `the index names ${row}, which the tree holds nothing of — a path ` +
          'that has moved or gone takes its reader nowhere, and the index is ' +
          'the whole of what the root guide keeps in place of the notes',
      )
    }
  })
  it('names every module of src somewhere in its index', function() {
    const rows = indexed()
    assert.deepEqual(
      allFilesFrom(path.join(ROOT, 'src')).map(slashed)
        .filter((one) => /\.m?js$/.test(one))
        .filter((one) => !rows.some((row) => globbed(row).test(one))),
      [],
      'cannot leave a module out of the index, one line naming what it is ' +
        'being the whole of what the root guide says about it — a module ' +
        'named nowhere is one a reader meets first in the code',
    )
  })
  it('holds every note a guide carries to a row of the index', function() {
    const rows = indexed()
    for (const guide of GUIDES) {
      assert.deepEqual(
        noted(guide)
          .filter((one) => !rows.some((row) => globbed(row).test(one))),
        [],
        `${guide} notes a file the index does not name — the two are one map, ` +
          'so a note reachable only by opening the guide it sits in is a ' +
          'derivation the root has stopped pointing at',
      )
    }
  })
  it('cannot note a file the guide does not stand above', function() {
    for (const guide of GUIDES) {
      assert.deepEqual(
        noted(guide)
          .filter((one) => !one.startsWith(`${path.dirname(guide)}/`)),
        [],
        `${guide} notes a file outside its own directory, where a reader ` +
          'opening that file loads some other guide — a note arrives with ' +
          'the directory it sits in, so it goes where its own code goes',
      )
    }
  })
  it('counts the attribute lists as long as they are, where it counts them', function() {
    const claimed = new RegExp(
      `(?:the|those|these|its|of)${GAP}+([a-z-]+)${GAP}+` +
      `(?:names|attributes|descendant scans)`, 'g',
    )
    const lengths = new Set(LENGTHS.values())
    for (const file of PROSE) {
      for (const [claim, word] of worded(file).matchAll(claimed)) {
        if (NUMBERS.has(word)) {
          assert.ok(
            lengths.has(NUMBERS.get(word)),
            `${file} says "${claim}", and neither ATTRIBUTES nor PATTERNS ` +
              `holds ${NUMBERS.get(word)} — say what the list holds, or make ` +
              'the claim about something a reader can count',
          )
        }
      }
    }
  })
  DERIVED.forEach((one) => {
    it(`states ${one.truth().join(' and ')} where the chain says so`,
      function() {
        assert.deepEqual(
          MEASURED.flatMap((file) => Array.from(
            worded(file).matchAll(one.claim),
            (hit) => `${file}: ${hit.slice(1).join(' and ')}`,
          )).filter(
            (said) => said.split(': ')[1] !== one.truth().join(' and '),
          ),
          [],
          `a figure derived from what the guides weigh says something the ` +
            `tree does not: ${one.truth().join(' and ')} is what the chain ` +
            'reads here, and the bar stays quiet until ' + LOADED +
            ', so nothing else catches this',
        )
      })
  })
  DERIVED.forEach((one) => {
    it(`reads ${one.truth().join(' and ')} in every file that states it`,
      function() {
        assert.deepEqual(
          MEASURED.filter((file) => carries(one.claim, worded(file))).sort(),
          one.carriers.slice().sort(),
          'the files carrying this figure are not the files it is watched ' +
            'in: a sentence reworded past the phrase drops out of the gate ' +
            'above while its figure stays wrong, and one written into a new ' +
            'document is watched nowhere — asking whether *some* file still ' +
            'matches would answer yes to both',
        )
      })
  })
  it('counts a list a document names against that very list', function() {
    const near = new RegExp(
      `(${[...LENGTHS.keys()].join('|')})(?=(.{0,${NEARBY}}))`, 'g',
    )
    const counted = new RegExp(
      `([a-z-]+)${GAP}+(?:names|attributes|descendant scans|selectors)`,
    )
    for (const file of DOCUMENTS) {
      for (const [, list, after] of worded(file).matchAll(near)) {
        const claim = after.match(counted)
        if (claim && NUMBERS.has(claim[1])) {
          assert.equal(
            NUMBERS.get(claim[1]), LENGTHS.get(list),
            `${file} names ${list} and calls it "${claim[0]}", where it holds ` +
              `${LENGTHS.get(list)} — the count beside a list is the one thing ` +
              'a reader takes on trust, so it answers to the list',
          )
        }
      }
    }
  })
})
